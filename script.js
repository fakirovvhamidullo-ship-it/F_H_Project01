let currentLang = 'ru';

function applyLang(lang){
  currentLang = lang;
  document.documentElement.lang = lang;
  const dict = translations[lang];
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key = el.getAttribute('data-i18n');
    if(dict[key] !== undefined) el.innerHTML = dict[key];
  });
  document.getElementById('langLabel').textContent = lang.toUpperCase();
  document.querySelectorAll('.lang-menu button').forEach(b=>{
    b.classList.toggle('active', b.getAttribute('data-lang')===lang);
  });
  renderCart();
}

document.getElementById('langBtn').addEventListener('click', (e)=>{
  e.stopPropagation();
  document.getElementById('langMenu').classList.toggle('open');
});
document.querySelectorAll('.lang-menu button').forEach(btn=>{
  btn.addEventListener('click', ()=>{
    applyLang(btn.getAttribute('data-lang'));
    document.getElementById('langMenu').classList.remove('open');
  });
});
document.addEventListener('click', ()=> document.getElementById('langMenu').classList.remove('open'));

/* ======================= Slider ======================= */
let slideIndex = 0;
const slideEls = document.querySelectorAll('.slide');
const dotsWrap = document.getElementById('dots');
slideEls.forEach((_,i)=>{
  const d = document.createElement('button');
  if(i===0) d.classList.add('active');
  d.addEventListener('click', ()=> goToSlide(i));
  dotsWrap.appendChild(d);
});
function renderSlides(){
  slideEls.forEach((s,i)=> s.classList.toggle('active', i===slideIndex));
  dotsWrap.querySelectorAll('button').forEach((d,i)=> d.classList.toggle('active', i===slideIndex));
}
function changeSlide(dir){
  slideIndex = (slideIndex + dir + slideEls.length) % slideEls.length;
  renderSlides();
  resetAutoplay();
}
function goToSlide(i){ slideIndex = i; renderSlides(); resetAutoplay(); }
let autoplay = setInterval(()=> changeSlide(1), 5500);
function resetAutoplay(){ clearInterval(autoplay); autoplay = setInterval(()=> changeSlide(1), 5500); }

/* ======================= Category tabs ======================= */
document.querySelectorAll('.cat-tab').forEach(tab=>{
  tab.addEventListener('click', ()=>{
    document.querySelectorAll('.cat-tab').forEach(t=>t.classList.remove('active'));
    tab.classList.add('active');
    document.querySelectorAll('.cat-panel').forEach(p=>p.classList.remove('active'));
    document.getElementById('panel-'+tab.getAttribute('data-target')).classList.add('active');
  });
});

/* ======================= Wishlist ======================= */
let wishCount = 0;
function toggleWish(btn){
  btn.classList.toggle('active');
  wishCount += btn.classList.contains('active') ? 1 : -1;
  document.getElementById('wishCount').textContent = wishCount;
  showToast(translations[currentLang][btn.classList.contains('active') ? 'toast_wish' : 'toast_wish_rm']);
}

/* ======================= Cart ======================= */
let cart = [];
function addToCart(btn, titleKey, price, img){
  cart.push({titleKey, price:Number(price), img});
  updateCartCount();
  renderCart();
  showToast(translations[currentLang].toast_added);
  btn.classList.add('added');
  btn.textContent = '✓';
  setTimeout(()=>{ btn.textContent = translations[currentLang].add_cart; btn.classList.remove('added'); }, 900);
}
function updateCartCount(){ document.getElementById('cartCount').textContent = cart.length; }
function renderCart(){
  const wrap = document.getElementById('cartItems');
  const dict = translations[currentLang];
  if(cart.length===0){
    wrap.innerHTML = `<p class="cart-empty">${dict.cart_empty}</p>`;
  } else {
    wrap.innerHTML = cart.map((item,i)=>`
      <div class="cart-row">
        <img src="${item.img}" alt="">
        <div class="ci-info">
          <div class="ci-title">${dict[item.titleKey] || item.titleKey}</div>
          <div class="ci-price">${item.price} ${dict.currency}</div>
        </div>
        <button class="ci-remove" onclick="removeFromCart(${i})">✕</button>
      </div>
    `).join('');
  }
  const total = cart.reduce((s,i)=> s+i.price, 0);
  document.getElementById('cartTotal').textContent = total + ' ' + dict.currency;
}
function removeFromCart(i){ cart.splice(i,1); updateCartCount(); renderCart(); }
function openCart(){ document.getElementById('cartDrawer').classList.add('open'); document.getElementById('drawerOverlay').classList.add('open'); }
function closeCart(){ document.getElementById('cartDrawer').classList.remove('open'); document.getElementById('drawerOverlay').classList.remove('open'); }
document.getElementById('cartBtn').addEventListener('click', openCart);
function checkout(){
  if(cart.length===0) return;
  showToast(translations[currentLang].toast_checkout);
  cart = [];
  updateCartCount();
  renderCart();
  closeCart();
}

/* ======================= Call modal ======================= */
function openCallModal(){
  document.getElementById('callModal').classList.add('open');
  document.getElementById('callForm').style.display = 'block';
  document.getElementById('callSuccess').style.display = 'none';
}
function closeCallModal(){
  document.getElementById('callModal').classList.remove('open');
  document.getElementById('callFormEl').reset();
}
document.getElementById('callModal').addEventListener('click', (e)=>{
  if(e.target.id === 'callModal') closeCallModal();
});
document.getElementById('callBtnHeader').addEventListener('click', openCallModal);
function submitCall(e){
  e.preventDefault();
  document.getElementById('callForm').style.display = 'none';
  document.getElementById('callSuccess').style.display = 'block';
}

/* ======================= Toast ======================= */
let toastTimer;
function showToast(msg){
  const t = document.getElementById('toast');
  t.textContent = msg;
  t.classList.add('show');
  clearTimeout(toastTimer);
  toastTimer = setTimeout(()=> t.classList.remove('show'), 2400);
}

